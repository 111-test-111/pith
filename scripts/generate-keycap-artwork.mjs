/** Convert the vendored Lucide shortcut SVGs into the shared icon adapter's
 * drawing data. Offline; no icon package or build-time dependency is needed. */
import { readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = join(repo, 'src/renderer/public/lucide-keycaps')
const drawings = {
  Command: 'command', Option: 'option', Control: 'chevron-up', Shift: 'arrow-big-up',
  Backspace: 'delete', KeyArrowLeft: 'arrow-left', KeyArrowRight: 'arrow-right',
  KeyArrowUp: 'arrow-up', KeyArrowDown: 'arrow-down'
}
const entries = []
for (const [name, slug] of Object.entries(drawings)) {
  const svg = await readFile(join(source, slug + '.svg'), 'utf8')
  if (!/viewBox="0 0 24 24"/.test(svg)) throw new Error(slug + ': unexpected canvas')
  // This pinned subset contains paths only. Reject a changed upstream format
  // rather than silently dropping part of an icon on a future refresh.
  const children = svg.replace(/<!--[\s\S]*?-->/g, '').match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1]
  if (!children || children.replace(/<path\s+d="[^"]+"\s*\/>/g, '').trim()) throw new Error(slug + ': unexpected artwork')
  const nodes = [...children.matchAll(/<path\s+d="([^"]+)"\s*\/>/g)].map(([, d], index) =>
    `    ['path', { d: ${JSON.stringify(d)}, stroke: 'currentColor', strokeWidth: UI_ICON_STROKE, strokeLinecap: 'round', strokeLinejoin: 'round', key: '${slug}-${index}' }]`
  )
  if (!nodes.length) throw new Error(slug + ': empty artwork')
  entries.push(`  ${name}: [\n${nodes.join(',\n')}\n  ]`)
}
const output = `// Generated by node scripts/generate-keycap-artwork.mjs. Preserve upstream paths.
// Lucide 1.50.0; SVG masters and ISC/Feather MIT notices: public/lucide-keycaps/.
import type { IconSvgElement } from '@hugeicons/react'
import { UI_ICON_STROKE } from './icon-metrics'

export const KEYCAP_ARTWORK = {
${entries.join(',\n')}
} as const satisfies Record<string, IconSvgElement>
`
await writeFile(join(repo, 'src/renderer/src/lib/keycap-artwork.ts'), output)
console.log('keycaps: ' + entries.length + ' vendored Lucide drawings')
